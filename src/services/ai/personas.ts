/**
 * AI karakter şablonları (persona kataloğu).
 *
 * Her şablon bir karakterin KİMLİĞİNİ tanımlar: adı, kısa profili, konuşma
 * tarzı ve davranış ölçekleri. Davranış motoru (`activity.ts`) ve metin
 * üreticisi (`voice.ts`) yalnızca bu veriden beslenir — mantık şablonlarda
 * gömülü değildir, böylece yeni bir karakter eklemek tek satırlık bir iş.
 *
 * Ölçekler 0.0–1.0 arasındadır ve doğrudan davranışa çevrilir:
 *   verbosity   yazı uzunluğu (0 = tek cümle … 1 = uzun açıklama)
 *   humor       espri/troll yoğunluğu
 *   assertiveness tartışmacılık (yüksek = kavgaya girer)
 *   politeness  nezaket
 *   activity    paylaşım sıklığı
 *   profanity   küfür eğilimi
 *   emoji_rate  emoji sıklığı
 *   comment_rate / post_rate  yorum / gönderi açma eğilimi
 *   upvote_bias / downvote_bias  oy verme yönelimi
 *
 * Kullanım: npm run seed:ai
 */

export interface Persona {
  /** Kullanıcı adı (unique, lowercase, 4+ karakter). */
  username: string
  /** Görünen ad. */
  displayName: string
  /** Şablon anahtarı; davranış motoru ve admin arayüzü bunu etiket olarak kullanır. */
  archetype: string
  /** Kısa karakter profili (bio). */
  bio: string
  /** Konuşma tarzı — metin üreticisinin cümle kurma biçimini belirler. */
  voice: string
  /**
   * Karakterin kendine özgü "söz kalıbı" (verbal tic). Her yorumda geçer,
   * böylece iki farklı karakterin cümlesi birbirinin kopyası olamaz.
   * 50 persona içinde benzersiz olmak ZORUNDADIR (test bunu doğrular).
   */
  tic: string
  verbosity: number
  humor: number
  assertiveness: number
  politeness: number
  activity: number
  profanity: number
  emoji_rate: number
  comment_rate: number
  post_rate: number
  upvote_bias: number
  downvote_bias: number
  /** İlgi alanları — konu seçimi ve yorum konusunu belirler. */
  interests: string[]
  /** Sevdiği konu türleri. */
  likes: string[]
  /** Sevmediği konu türleri. */
  dislikes: string[]
  /** Varsayılan board tercihleri (ağırlık 0–1). Boşsa herkese açık. */
  boardPrefs: Record<string, number>
  /** Diğer karakterlerle uyum eğilimi: kullanıcı adına göre ağırlık (-1..1). */
  peers: Record<string, number>
}

