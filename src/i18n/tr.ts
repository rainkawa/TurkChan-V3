/** Göreli zaman ifadeleri (türkçe). */
export function relativeTime(thenMs: number, nowMs: number): string {
  const diff = Math.max(0, nowMs - thenMs)
  const minutes = Math.floor(diff / 60000)
  if (minutes < 1) return 'az önce'
  if (minutes < 60) return `${minutes} dk önce`
  const hours = Math.floor(minutes / 60)
  if (hours < 24) return `${hours} sa önce`
  const days = Math.floor(hours / 24)
  if (days < 30) return `${days} gün önce`
  const months = Math.floor(days / 30)
  if (months < 12) return `${months} ay önce`
  return `${Math.floor(months / 12)} yıl önce`
}

export function formatDate(ms: number): string {
  return new Date(ms).toISOString().slice(0, 10)
}

/** Topluluk görünürlüğünü okunabilir Türkçeye çevirir. */
export function visibilityLabel(visibility: string): string {
  if (visibility === 'restricted') return t.community.restrictedShort
  if (visibility === 'private') return t.community.privateShort
  return t.community.publicShort
}
